/** Spec §2.3 / §55: business code depends on this interface only; uploads live outside the app container. */
export interface StorageProvider {
  readonly name: string;
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Missing objects are not an error: deletes must be safe to retry. */
  delete(key: string): Promise<void>;
}

export class StorageError extends Error {
  constructor(
    public readonly code: 'INVALID_KEY' | 'NOT_FOUND' | 'UNAVAILABLE',
    message: string,
  ) {
    super(message);
    this.name = 'StorageError';
  }
}

// Keys are generated by the app (org/…/doc/…), never taken from user input; this is defense in depth.
const KEY = /^[A-Za-z0-9][A-Za-z0-9/_.-]{0,511}$/;

export function assertValidKey(key: string): void {
  if (!KEY.test(key) || key.split('/').some((p) => p === '' || p === '.' || p === '..')) {
    throw new StorageError('INVALID_KEY', 'Invalid storage key');
  }
}
